/* Inline x86-64 detour engine for hooking `@:hlNative` functions.
 *
 * HL bytecode functions are hookable because their JIT-compiled bodies carry
 * an injected prologue check (jit_hook_call). Natives have no such body:
 * they are raw dlsym'd C pointers, and every caller bakes the resolved
 * address in as an immediate constant at JIT-compile time (see
 * op_call_fun's native branch in jit.c). Patching functions_ptrs[findex]
 * after the fact does nothing for callers already compiled, so the only way
 * to intercept an already-running native is to redirect its own machine code
 * at the address every caller already has. This file does exactly that:
 * a conservative length disassembler finds a safe prologue to overwrite, a
 * copy of the overwritten bytes plus a jump back becomes the "call original"
 * path, and the landing stub is generated by hl_jit_native_hook_adapter
 * (jit.c), which reuses the same dispatch (jit_dispatch_hook) and Python
 * hook chain (modcore._hooks) already used for bytecode functions.
 *
 * Deliberately narrow and fails loudly: if the length disassembler cannot
 * confidently account for at least 12 bytes of linear, non-branching
 * instructions at the native's entry point, hooking is refused with a clear
 * Python exception rather than guessing at an instruction boundary. Only
 * x86-64 targets are supported, matching the only architectures hlmod-hl's
 * JIT itself targets. */

#include "native_hook.h"
#include <string.h>
#include <stdint.h>
#include <stdio.h>

